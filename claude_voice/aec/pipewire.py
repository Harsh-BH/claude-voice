"""WebRTC AEC3 echo cancellation as a supervised, standalone PipeWire client.

`pipewire -c <conf>` loads libpipewire-module-echo-cancel in its own process, so:
- the user's PipeWire/WirePlumber configuration is never touched;
- the nodes exist only while voice mode runs (an idle canceller would still pull the mic along
  whenever anything plays, because its capture and reference streams share one graph driver);
- `setpriv --pdeathsig TERM` kills it if we die, so a crash cannot leave the mic open.

Monitor mode (default) uses the monitor of the default sink as the echo reference: exactly what
reaches the speaker, after EasyEffects or any other processing, including music and videos.
Sink mode creates a dedicated sink for Claude's voice only.

`node.dont-move` keeps EasyEffects' "process all inputs" from re-routing the canceller's
capture stream through its own chain (observed on this machine).
"""
from __future__ import annotations

import logging
import re
import shutil
import subprocess
import time

from claude_voice.config import RUNTIME_DIR, STATE_DIR, AecConfig

log = logging.getLogger(__name__)

SOURCE = "claude_voice_aec_source"
SINK = "claude_voice_aec_sink"
REFERENCE = "claude_voice.aec.reference"
CAPTURE = "claude_voice.aec.capture"
_NODE_NAME = re.compile(r"^[A-Za-z0-9._:-]+$")

_TEMPLATE = """\
# Generated by claude-voice on every start; edit [aec] in config.toml instead.
context.properties = {{ log.level = 2 }}
context.spa-libs = {{
    audio.convert.* = audioconvert/libspa-audioconvert
    support.*       = support/libspa-support
}}
context.modules = [
    {{ name = libpipewire-module-rt args = {{ }} flags = [ ifexists nofail ] }}
    {{ name = libpipewire-module-protocol-native }}
    {{ name = libpipewire-module-client-node }}
    {{ name = libpipewire-module-adapter }}
    {{ name = libpipewire-module-echo-cancel
      args = {{
        library.name = aec/libspa-aec-webrtc
        monitor.mode = {monitor}
        audio.rate = 48000
        audio.channels = 1
        audio.position = [ MONO ]
        aec.args = {{
            webrtc.high_pass_filter = {hpf}
            webrtc.noise_suppression = {ns}
            webrtc.transient_suppression = {ts}
            webrtc.gain_control = {agc}
        }}
        capture.props = {{ node.name = "{capture}" node.passive = true node.dont-move = true {mic} }}
        source.props = {{ node.name = "{source}" node.description = "Claude Voice echo-cancelled mic" }}
        sink.props = {{ node.name = "{sink}" node.description = "Claude Voice echo reference" node.dont-move = true {sink_extra} }}
        playback.props = {{ node.name = "claude_voice.aec.playback" node.passive = true node.dont-move = true {speaker} }}
      }}
    }}
]
"""


def render(cfg: AecConfig, mic: str = "", speaker: str = "") -> str:
    """mic/speaker: node names to pin, "" to follow the defaults."""
    for name in (mic, speaker):
        if name and not _NODE_NAME.match(name):
            raise ValueError(f"not a valid PipeWire node name: {name!r}")
    monitor = cfg.mode == "monitor"
    b = lambda v: "true" if v else "false"  # noqa: E731
    target = lambda n: f'target.object = "{n}"' if n else ""  # noqa: E731
    # "<sink>.monitor" (pulse naming) means: capture that sink's monitor ports
    mic_props = (f'{target(mic.removesuffix(".monitor"))} stream.capture.sink = true'
                 if mic.endswith(".monitor") else target(mic))
    return _TEMPLATE.format(
        monitor=b(monitor), hpf=b(cfg.high_pass_filter), ns=b(cfg.noise_suppression),
        ts=b(cfg.transient_suppression), agc=b(cfg.gain_control), capture=CAPTURE, source=SOURCE,
        mic=mic_props,
        sink=REFERENCE if monitor else SINK,
        # monitor mode: the "sink" is a passive capture of the speaker's monitor ports
        sink_extra=f"node.passive = true {target(speaker)}" if monitor else "",
        speaker=target(speaker),
    )


def pactl_names(kind: str) -> list[str]:
    try:
        out = subprocess.run(["pactl", "list", "short", kind], capture_output=True, text=True, timeout=3).stdout
    except (OSError, subprocess.TimeoutExpired):
        return []
    return [line.split("\t")[1] for line in out.splitlines() if "\t" in line]


def links() -> dict[str, list[str]]:
    """Port links touching our nodes, as {our_port: [peer ports]} (for doctor and tests)."""
    try:
        out = subprocess.run(["pw-link", "-l"], capture_output=True, text=True, timeout=3).stdout
    except (OSError, subprocess.TimeoutExpired):
        return {}
    result: dict[str, list[str]] = {}
    current = None
    for line in out.splitlines():
        if not line.startswith(" "):
            current = line.strip() if "claude_voice" in line else None
        elif current and ("|<-" in line or "|->" in line):
            result.setdefault(current, []).append(line.split("-", 1)[1].lstrip("<> ").strip())
    return result


class EchoCanceller:
    def __init__(self, cfg: AecConfig, mic: str = "", speaker: str = ""):
        self.cfg, self.mic, self.speaker = cfg, mic, speaker
        self.proc: subprocess.Popen | None = None
        self.conf = RUNTIME_DIR / "aec.conf"
        self.restarts = 0

    @property
    def playback_sink(self) -> str | None:
        """Where Claude's voice must go for the canceller to see it (None = default sink)."""
        return (self.speaker or None) if self.cfg.mode == "monitor" else SINK

    def start(self, timeout: float = 6.0) -> None:
        """Must be called from the main/event-loop thread: pdeathsig fires when the spawning thread exits."""
        RUNTIME_DIR.mkdir(parents=True, exist_ok=True)
        STATE_DIR.mkdir(parents=True, exist_ok=True)
        self.conf.write_text(render(self.cfg, self.mic, self.speaker))
        # a canceller left behind by a SIGKILLed run would give two sources with the same name
        subprocess.run(["pkill", "-f", f"pipewire -c {self.conf}"], capture_output=True)
        cmd = ["pipewire", "-c", str(self.conf)]
        if shutil.which("setpriv"):
            cmd = ["setpriv", "--pdeathsig", "TERM", "--", *cmd]
        logf = open(STATE_DIR / "aec.log", "ab")
        self.proc = subprocess.Popen(cmd, stdout=logf, stderr=subprocess.STDOUT, stdin=subprocess.DEVNULL)
        logf.close()
        deadline = time.monotonic() + timeout
        while time.monotonic() < deadline:
            if self.proc.poll() is not None:
                raise RuntimeError(f"echo canceller exited with {self.proc.returncode}; see {STATE_DIR / 'aec.log'}")
            if SOURCE in pactl_names("sources"):
                log.info("echo canceller up (%s mode, pid %s)", self.cfg.mode, self.proc.pid)
                return
            time.sleep(0.05)
        self.stop()
        raise RuntimeError("echo canceller did not create its source in time")

    def alive(self) -> bool:
        return self.proc is not None and self.proc.poll() is None

    def ensure(self) -> bool:
        """Restart a crashed canceller; True if a restart happened."""
        if self.proc is None or self.alive():
            return False
        log.warning("echo canceller died (code %s); restarting", self.proc.returncode)
        self.restarts += 1
        self.start()
        return True

    def stop(self) -> None:
        if self.proc is None:
            return
        if self.proc.poll() is None:
            self.proc.terminate()
            try:
                self.proc.wait(2)
            except subprocess.TimeoutExpired:
                self.proc.kill()
                self.proc.wait(2)
        self.proc = None
